import type {
	RuntimeAgentId,
	RuntimeBoardColumnId,
	RuntimeCodexOptions,
	RuntimeConflictState,
	RuntimePersistedClaudeOptions,
	RuntimeTaskImageInput,
} from "@/runtime/types";

export type BoardColumnId = RuntimeBoardColumnId;

/** A stored reference from the runtime, or an inline upload not yet committed. */
export type TaskImage = RuntimeTaskImageInput;

export interface BoardCard {
	id: string;
	title: string | null;
	titleAutoGenerated?: boolean;
	prompt: string;
	images?: TaskImage[];
	baseRef: string;
	baseRefPinned?: boolean;
	agentId?: RuntimeAgentId;
	codexOptions?: RuntimeCodexOptions;
	claudeOptions?: RuntimePersistedClaudeOptions;
	useWorktree?: boolean;
	workingDirectory?: string | null;
	branch?: string | null;
	pinned?: boolean;
	colorIndex?: number;
	unstarted?: boolean;
	createdAt: number;
	updatedAt: number;
}

export interface BoardColumn {
	id: BoardColumnId;
	title: string;
	cards: BoardCard[];
}

export interface BoardData {
	columns: BoardColumn[];
}

export interface ReviewTaskWorktreeSnapshot {
	taskId: string;
	path: string;
	baseRef?: string;
	branch: string | null;
	isDetached: boolean;
	headCommit: string | null;
	changedFiles: number | null;
	additions: number | null;
	deletions: number | null;
	hasUnmergedChanges: boolean | null;
	behindBaseCount: number | null;
	behindRemoteBaseCount: number | null;
	conflictState: RuntimeConflictState | null;
}

export interface CardSelection {
	card: BoardCard;
	column: BoardColumn;
	allColumns: BoardColumn[];
}
