import { describe, expect, it } from "vitest";

import type { RuntimeBoardData, RuntimeProjectBoardCommand } from "../../src/core";
import {
	applyProjectBoardCommand,
	runtimeClaudeOptionsSchema,
	runtimeCodexOptionsSchema,
	runtimePiOptionsSchema,
	runtimeProjectBoardCommandSchema,
	runtimeTaskLifecycleCommandSchema,
} from "../../src/core";

function createBoard(): RuntimeBoardData {
	return {
		columns: [
			{ id: "in_progress", title: "In Progress", cards: [] },
			{ id: "review", title: "Review", cards: [] },
			{ id: "trash", title: "Trash", cards: [] },
		],
	};
}

function createTaskCommand(taskId: string, prompt: string, createdAt: number): RuntimeProjectBoardCommand {
	return {
		kind: "create_task",
		columnId: "review",
		taskId,
		prompt,
		baseRef: "main",
		agentId: "codex",
		useWorktree: true,
		createdAt,
	};
}

describe("applyProjectBoardCommand", () => {
	it("keeps pinned trash tasks in deletion batches until explicitly unpinned", () => {
		let board = createBoard();
		for (const taskId of ["kept", "deleted"]) {
			board = applyProjectBoardCommand(board, {
				kind: "create_task",
				columnId: "trash",
				taskId,
				prompt: taskId,
				baseRef: "main",
				createdAt: 1,
				pinned: taskId === "kept",
			}).board;
		}
		board = applyProjectBoardCommand(board, { kind: "delete_tasks", taskIds: ["kept", "deleted"] }).board;
		expect(board.columns.find((column) => column.id === "trash")?.cards.map((card) => card.id)).toEqual(["kept"]);
		board = applyProjectBoardCommand(board, {
			kind: "update_task",
			taskId: "kept",
			prompt: "kept",
			baseRef: "main",
			pinned: false,
			updatedAt: 2,
		}).board;
		board = applyProjectBoardCommand(board, { kind: "delete_tasks", taskIds: ["kept"] }).board;
		expect(board.columns.find((column) => column.id === "trash")?.cards).toEqual([]);
	});

	it("creates tasks with command-owned identity and timestamps", () => {
		const command = createTaskCommand("task-a", "  Ship it  ", 100);
		const result = applyProjectBoardCommand(createBoard(), command);
		const replayed = applyProjectBoardCommand(result.board, command);

		expect(result.changed).toBe(true);
		expect(result.board.columns.find((column) => column.id === "review")?.cards).toEqual([
			{
				id: "task-a",
				colorIndex: expect.any(Number),
				unstarted: true,
				title: null,
				prompt: "Ship it",
				baseRef: "main",
				agentId: "codex",
				useWorktree: true,
				createdAt: 100,
				updatedAt: 100,
			},
		]);
		expect(replayed.changed).toBe(false);
		expect(replayed.board).toBe(result.board);
	});

	it("applies update, move, and delete commands through shared reducers", () => {
		const first = applyProjectBoardCommand(createBoard(), createTaskCommand("task-a", "Task A", 100));
		const second = applyProjectBoardCommand(first.board, createTaskCommand("task-b", "Task B", 110));
		const moved = applyProjectBoardCommand(second.board, {
			kind: "move_task",
			taskId: "task-b",
			targetColumnId: "in_progress",
			updatedAt: 120,
		});
		const updateCommand: RuntimeProjectBoardCommand = {
			kind: "update_task",
			taskId: "task-a",
			title: "Task A title",
			prompt: "Updated Task A",
			baseRef: "develop",
			useWorktree: false,
			pinned: true,
			updatedAt: 140,
		};
		const updated = applyProjectBoardCommand(moved.board, updateCommand);
		const replayedUpdate = applyProjectBoardCommand(updated.board, updateCommand);
		const deleted = applyProjectBoardCommand(updated.board, {
			kind: "delete_tasks",
			taskIds: ["task-b"],
		});

		expect(moved.changed).toBe(true);
		expect(moved.board.columns.find((column) => column.id === "in_progress")?.cards[0]?.updatedAt).toBe(120);
		expect(updated.board.columns.find((column) => column.id === "review")?.cards[0]).toMatchObject({
			id: "task-a",
			title: "Task A title",
			prompt: "Updated Task A",
			baseRef: "develop",
			useWorktree: false,
			pinned: true,
			updatedAt: 140,
		});
		expect(replayedUpdate.changed).toBe(false);
		expect(replayedUpdate.board).toBe(updated.board);
		expect(deleted.changed).toBe(true);
		expect(deleted.board.columns.flatMap((column) => column.cards).map((card) => card.id)).toEqual(["task-a"]);
	});

	it("does not report missing-task commands as changes", () => {
		const board = createBoard();
		const moved = applyProjectBoardCommand(board, {
			kind: "move_task",
			taskId: "missing",
			targetColumnId: "review",
			updatedAt: 100,
		});

		expect(moved).toEqual({ board, changed: false });
	});

	it.each(["patch_task", "update_task"] as const)(
		"an explicit %s title takes manual ownership even when unchanged",
		(kind) => {
			const { board } = applyProjectBoardCommand(createBoard(), createTaskCommand("task-a", "Task A", 100));
			const card = board.columns.find((column) => column.id === "review")?.cards[0];
			if (!card) throw new Error("Missing test card");
			card.title = "Generated";
			card.titleAutoGenerated = true;
			const result = applyProjectBoardCommand(board, {
				kind,
				taskId: "task-a",
				title: "Generated",
				prompt: "Task A",
				baseRef: "main",
				updatedAt: 100,
			});
			expect(result.changed).toBe(true);
			expect(result.board.columns.find((column) => column.id === "review")?.cards[0]).toMatchObject({
				title: "Generated",
				titleAutoGenerated: false,
			});
		},
	);

	it("metadata patches preserve generated title ownership", () => {
		const { board } = applyProjectBoardCommand(createBoard(), createTaskCommand("task-a", "Task A", 100));
		const card = board.columns.find((column) => column.id === "review")?.cards[0];
		if (!card) throw new Error("Missing test card");
		card.titleAutoGenerated = true;
		const result = applyProjectBoardCommand(board, {
			kind: "patch_task",
			taskId: "task-a",
			pinned: true,
			updatedAt: 200,
		});
		expect(result.board.columns.find((column) => column.id === "review")?.cards[0]?.titleAutoGenerated).toBe(true);
	});

	it("reorders cards and patches runtime-owned metadata deterministically", () => {
		const first = applyProjectBoardCommand(createBoard(), createTaskCommand("task-a", "Task A", 100));
		const second = applyProjectBoardCommand(first.board, createTaskCommand("task-b", "Task B", 110));
		const third = applyProjectBoardCommand(second.board, createTaskCommand("task-c", "Task C", 120));

		const reordered = applyProjectBoardCommand(third.board, {
			kind: "reorder_task",
			taskId: "task-a",
			columnId: "review",
			targetIndex: 0,
		});
		const patched = applyProjectBoardCommand(reordered.board, {
			kind: "patch_task",
			taskId: "task-a",
			branch: "feature/task-a",
			workingDirectory: "/tmp/task-a",
			baseRefPinned: true,
			updatedAt: 130,
		});
		const repeatedPatch = applyProjectBoardCommand(patched.board, {
			kind: "patch_task",
			taskId: "task-a",
			branch: "feature/task-a",
			workingDirectory: "/tmp/task-a",
			baseRefPinned: true,
			updatedAt: 140,
		});

		expect(reordered.changed).toBe(true);
		expect(reordered.board.columns.find((column) => column.id === "review")?.cards.map((card) => card.id)).toEqual([
			"task-a",
			"task-c",
			"task-b",
		]);
		expect(patched.changed).toBe(true);
		expect(patched.board.columns.find((column) => column.id === "review")?.cards[0]).toMatchObject({
			id: "task-a",
			branch: "feature/task-a",
			workingDirectory: "/tmp/task-a",
			baseRefPinned: true,
			updatedAt: 130,
		});
		expect(repeatedPatch.changed).toBe(false);
		expect(repeatedPatch.board).toBe(patched.board);
	});

	it("reorders a whole column atomically and ignores stale membership", () => {
		const first = applyProjectBoardCommand(createBoard(), createTaskCommand("task-a", "Task A", 100));
		const second = applyProjectBoardCommand(first.board, createTaskCommand("task-b", "Task B", 110));
		const reordered = applyProjectBoardCommand(second.board, {
			kind: "reorder_column",
			columnId: "review",
			taskIds: ["task-a", "task-b"],
		});

		expect(reordered.changed).toBe(true);
		expect(reordered.board.columns.find((column) => column.id === "review")?.cards.map((card) => card.id)).toEqual([
			"task-a",
			"task-b",
		]);
		expect(
			applyProjectBoardCommand(reordered.board, {
				kind: "reorder_column",
				columnId: "review",
				taskIds: ["task-a"],
			}),
		).toEqual({ board: reordered.board, changed: false });
	});

	it("inserts cross-column moves at the requested position", () => {
		const first = applyProjectBoardCommand(createBoard(), createTaskCommand("task-a", "Task A", 100));
		const second = applyProjectBoardCommand(first.board, createTaskCommand("task-b", "Task B", 110));
		const movedA = applyProjectBoardCommand(second.board, {
			kind: "move_task",
			taskId: "task-a",
			targetColumnId: "review",
			updatedAt: 120,
		});
		const movedB = applyProjectBoardCommand(movedA.board, {
			kind: "move_task",
			taskId: "task-b",
			targetColumnId: "review",
			targetIndex: 0,
			updatedAt: 130,
		});

		expect(movedB.board.columns.find((column) => column.id === "review")?.cards.map((card) => card.id)).toEqual([
			"task-b",
			"task-a",
		]);
	});

	it("does not move a task when the source-column precondition is stale", () => {
		const created = applyProjectBoardCommand(createBoard(), createTaskCommand("task-a", "Task A", 100));
		const result = applyProjectBoardCommand(created.board, {
			kind: "move_task",
			taskId: "task-a",
			sourceColumnId: "trash",
			targetColumnId: "in_progress",
			updatedAt: 120,
		});

		expect(result).toEqual({ board: created.board, changed: false });
	});
});

describe("runtimeProjectBoardCommandSchema", () => {
	it("strips server-owned title provenance from client commands", () => {
		const command = runtimeProjectBoardCommandSchema.parse({
			...createTaskCommand("task-a", "Task A", 100),
			title: "Manual",
			titleAutoGenerated: true,
		});
		expect(command).not.toHaveProperty("titleAutoGenerated");
		const result = applyProjectBoardCommand(createBoard(), command);
		expect(result.board.columns.find((column) => column.id === "review")?.cards[0]?.titleAutoGenerated).not.toBe(
			true,
		);
		expect(
			runtimeProjectBoardCommandSchema.parse({
				kind: "patch_task",
				taskId: "task-a",
				titleAutoGenerated: true,
				updatedAt: 200,
			}),
		).not.toHaveProperty("titleAutoGenerated");
	});

	it("accepts every maintained agent for new commands", () => {
		expect(runtimeProjectBoardCommandSchema.safeParse(createTaskCommand("task-a", "Task A", 100)).success).toBe(true);
		expect(
			runtimeProjectBoardCommandSchema.safeParse({
				...createTaskCommand("task-a", "Task A", 100),
				agentId: "pi",
			}).success,
		).toBe(true);
	});
});

describe("runtimeTaskLifecycleCommandSchema", () => {
	it("accepts Pi for create-and-start", () => {
		expect(
			runtimeTaskLifecycleCommandSchema.safeParse({
				kind: "create_and_start",
				operationId: "create-and-start-pi",
				expectedRevision: 0,
				startedAt: 100,
				task: {
					taskId: "task-pi",
					prompt: "Use Pi",
					baseRef: "main",
					agentId: "pi",
					createdAt: 100,
				},
			}).success,
		).toBe(true);
	});
});

describe("starting Codex option validation", () => {
	it("accepts provider model and effort identifiers without a hardcoded catalog", () => {
		expect(runtimeCodexOptionsSchema.parse({ model: " provider/model-1 ", reasoningEffort: "future_level" })).toEqual(
			{
				model: "provider/model-1",
				reasoningEffort: "future_level",
			},
		);
	});
	it.each([
		{ model: "" },
		{ model: "-invalid" },
		{ model: "x".repeat(129) },
		{ reasoningEffort: "" },
		{ reasoningEffort: "high\nother" },
	])("rejects malformed options %j", (options) => {
		expect(runtimeCodexOptionsSchema.safeParse(options).success).toBe(false);
	});
});

describe("starting Claude options", () => {
	it("accepts Claude CLI model aliases or full ids and documented effort levels", () => {
		expect(runtimeClaudeOptionsSchema.parse({ model: " opus ", effort: "xhigh" })).toEqual({
			model: "opus",
			effort: "xhigh",
		});
		expect(runtimeClaudeOptionsSchema.parse({ model: "claude-opus-4-5-20251101" }).model).toBe(
			"claude-opus-4-5-20251101",
		);
	});

	it.each([{ model: "" }, { model: "-invalid" }, { effort: "ultra" }, { effort: "" }])(
		"rejects malformed options %j",
		(options) => {
			expect(runtimeClaudeOptionsSchema.safeParse(options).success).toBe(false);
		},
	);

	it("round-trips claudeOptions through create_task commands", () => {
		const command = runtimeProjectBoardCommandSchema.parse({
			...createTaskCommand("task-claude", "Ship it", 100),
			agentId: "claude",
			claudeOptions: { model: "sonnet", effort: "high" },
		});
		const result = applyProjectBoardCommand(createBoard(), command);
		const card = result.board.columns.find((column) => column.id === "review")?.cards[0];
		expect(card?.claudeOptions).toEqual({ model: "sonnet", effort: "high" });
		expect(applyProjectBoardCommand(result.board, command).changed).toBe(false);
	});

	it("stores provider starting options only for the owning agent", () => {
		const command = runtimeProjectBoardCommandSchema.parse({
			...createTaskCommand("task-codex", "Ship it", 100),
			agentId: "codex",
			codexOptions: { model: "codex-model" },
			claudeOptions: { model: "sonnet", effort: "high" },
		});
		const card = applyProjectBoardCommand(createBoard(), command).board.columns.find(
			(column) => column.id === "review",
		)?.cards[0];
		expect(card?.codexOptions).toEqual({ model: "codex-model" });
		expect(card?.claudeOptions).toBeUndefined();
	});

	it("accepts claudeOptions on create_and_start lifecycle commands", () => {
		const parsed = runtimeTaskLifecycleCommandSchema.parse({
			kind: "create_and_start",
			operationId: "operation-1",
			expectedRevision: 0,
			startedAt: 100,
			task: {
				taskId: "task-claude",
				prompt: "Ship it",
				baseRef: "main",
				agentId: "claude",
				claudeOptions: { model: "fable", effort: "max" },
				createdAt: 100,
			},
		});
		expect(parsed.kind === "create_and_start" ? parsed.task.claudeOptions : undefined).toEqual({
			model: "fable",
			effort: "max",
		});
	});

	it.each(["off", "minimal", "low", "medium", "high", "xhigh", "max"])(
		"accepts independent Pi thinking level %s and rejects unsupported values",
		(thinkingLevel) => {
			expect(runtimePiOptionsSchema.parse({ thinkingLevel })).toEqual({ thinkingLevel });
			for (const invalid of ["", "ultra", "none", "High", " high ", null, 1]) {
				expect(runtimePiOptionsSchema.safeParse({ thinkingLevel: invalid }).success).toBe(false);
			}
		},
	);

	it("validates Pi choices, retains them through create/start schemas, and detects changed provider identity", () => {
		const piOptions = { model: { provider: "alpha", id: "same-model:7b" }, thinkingLevel: "high" as const };
		expect(runtimePiOptionsSchema.parse({})).toEqual({});
		for (const model of [
			{ id: "missing-provider" },
			{ provider: "alpha", id: "bad\nmodel" },
			{ provider: "alpha", id: "--flag" },
		]) {
			expect(runtimePiOptionsSchema.safeParse({ model }).success).toBe(false);
		}
		const command = runtimeProjectBoardCommandSchema.parse({
			...createTaskCommand("pi-task", "Pi task", 100),
			agentId: "pi",
			piOptions,
		});
		if (command.kind !== "create_task") throw new Error("Expected create command");
		const created = applyProjectBoardCommand(createBoard(), command);
		expect(created.board.columns[1]?.cards[0]?.piOptions).toEqual(piOptions);
		expect(applyProjectBoardCommand(created.board, command).changed).toBe(false);
		expect(() =>
			applyProjectBoardCommand(created.board, {
				...command,
				agentId: "pi",
				piOptions: { model: { provider: "beta", id: "same-model:7b" } },
			}),
		).toThrow("different data");
		for (const thinkingLevel of [undefined, "low"] as const) {
			expect(() =>
				applyProjectBoardCommand(created.board, { ...command, piOptions: { ...piOptions, thinkingLevel } }),
			).toThrow("different data");
		}
		const parsed = runtimeTaskLifecycleCommandSchema.parse({
			kind: "create_and_start",
			operationId: "pi-op",
			expectedRevision: 0,
			startedAt: 100,
			task: { taskId: "pi-task", prompt: "Pi task", baseRef: "main", agentId: "pi", piOptions, createdAt: 100 },
		});
		expect(parsed.kind === "create_and_start" && parsed.task.piOptions).toEqual(piOptions);
	});

	// Older runtimes strip additive provider options instead of rejecting create intent.
	it("strips unknown task fields instead of rejecting the command", () => {
		const parsed = runtimeProjectBoardCommandSchema.safeParse({
			...createTaskCommand("task-future", "Ship it", 100),
			futureAgentOptions: { model: "next" },
		});
		expect(parsed.success).toBe(true);
		expect(parsed.success && "futureAgentOptions" in parsed.data).toBe(false);
	});
});
