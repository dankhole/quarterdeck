import type * as FsPromises from "node:fs/promises";
import { mkdir, readFile, rename, writeFile } from "node:fs/promises";
import { join } from "node:path";

import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";

import type { RuntimeBoardData } from "../../../src/core";
import { lockedFileSystem } from "../../../src/fs/locked-file-system";
import { createNativeTaskTitleMonitor } from "../../../src/server/native-task-title-monitor";
import { applyProjectBoardMutationById, ProjectBoardCommandService, ProjectBoardReadCache } from "../../../src/state";
import { getProjectStateTransactionPath } from "../../../src/state/project-state-transaction";
import {
	getProjectBoardPath,
	getProjectDirectoryPath,
	getProjectIndexPath,
	getProjectMetaPath,
	getProjectsRootPath,
} from "../../../src/state/project-state-utils";
import { InMemorySessionSummaryStore } from "../../../src/terminal";
import { createReviewBoard } from "../../utilities/board-factory";
import { createTestTaskSessionSummary } from "../../utilities/task-session-factory";
import { createTempDir } from "../../utilities/temp-dir";

const readFileCalls = vi.hoisted(() => ({ paths: [] as string[] }));

vi.mock("node:fs/promises", async (importOriginal) => {
	const actual = await importOriginal<typeof FsPromises>();
	return {
		...actual,
		readFile: ((path: Parameters<typeof actual.readFile>[0], ...rest: unknown[]) => {
			readFileCalls.paths.push(String(path));
			return (actual.readFile as (...args: unknown[]) => Promise<unknown>)(path, ...rest);
		}) as typeof actual.readFile,
	};
});

const projectId = "project-1";
const projectPath = "/synthetic/project";
const originalStateHome = process.env.QUARTERDECK_STATE_HOME;
let cleanup = () => {};

function stateFileReads(): string[] {
	const watched = new Set([getProjectBoardPath(projectId), getProjectMetaPath(projectId)]);
	return readFileCalls.paths.filter((path) => watched.has(path));
}

function spyOnProjectLocks() {
	const withLock = vi.spyOn(lockedFileSystem, "withLock");
	return () => withLock.mock.calls.filter(([request]) => request.path === getProjectDirectoryPath(projectId)).length;
}

function titleOf(board: RuntimeBoardData): string | null {
	return board.columns.flatMap((column) => column.cards).find((card) => card.id === "task-1")?.title ?? null;
}

async function seedProject(): Promise<void> {
	await mkdir(getProjectsRootPath(), { recursive: true });
	await mkdir(getProjectDirectoryPath(projectId), { recursive: true });
	await writeFile(
		getProjectIndexPath(),
		JSON.stringify({
			version: 1,
			entries: { [projectId]: { projectId, repoPath: projectPath } },
			repoPathToId: { [projectPath]: projectId },
		}),
		"utf8",
	);
	const board = createReviewBoard("task-1", "Fix title syncing");
	for (const card of board.columns.flatMap((column) => column.cards)) {
		Object.assign(card, { title: "Generated Title", titleAutoGenerated: true });
	}
	await applyProjectBoardMutationById(projectId, { sessions: {}, mutate: () => ({ board, changed: true }) });
}

/** Another process's commit: a complete atomic replacement this runtime never installed. */
async function replaceExternally(path: string, mutate: (value: Record<string, unknown>) => void): Promise<void> {
	const value = JSON.parse(await readFile(path, "utf8")) as Record<string, unknown>;
	mutate(value);
	await writeFile(`${path}.external`, JSON.stringify(value, null, 2), "utf8");
	await rename(`${path}.external`, path);
}

beforeEach(async () => {
	const temp = createTempDir("quarterdeck-board-read-cache-");
	cleanup = temp.cleanup;
	process.env.QUARTERDECK_STATE_HOME = join(temp.path, "state");
	await seedProject();
	readFileCalls.paths.length = 0;
});

afterEach(() => {
	vi.restoreAllMocks();
	cleanup();
	if (originalStateHome === undefined) delete process.env.QUARTERDECK_STATE_HOME;
	else process.env.QUARTERDECK_STATE_HOME = originalStateHome;
});

describe("ProjectBoardReadCache", { concurrent: false }, () => {
	it("serves repeated reads of an unchanged board and revision without the project lock or a file read", async () => {
		const cache = new ProjectBoardReadCache();
		const first = await cache.loadBoard(projectId);
		const revision = await cache.loadBoardRevision(projectId);
		expect(revision).toBe(1);
		expect(Object.isFrozen(first.columns[1]?.cards[0])).toBe(true);

		readFileCalls.paths.length = 0;
		const projectLocks = spyOnProjectLocks();
		for (let poll = 0; poll < 5; poll += 1) {
			expect(await cache.loadBoard(projectId)).toBe(first);
			expect(await cache.loadBoardRevision(projectId)).toBe(revision);
		}
		expect(projectLocks()).toBe(0);
		expect(stateFileReads()).toEqual([]);
	});

	it("rereads under the lock after a commit through the board command service", async () => {
		const cache = new ProjectBoardReadCache();
		const before = await cache.loadBoard(projectId);
		await cache.loadBoardRevision(projectId);
		const service = new ProjectBoardCommandService({ getAuthoritativeSessions: () => ({}) });
		const result = await service.setGeneratedTaskTitle(
			{ projectId, projectPath },
			"task-1",
			before.columns[1]?.cards[0]?.createdAt ?? 0,
			"Committed Title",
			Date.now(),
			{ expectedTitle: "Generated Title", expectedAutoGenerated: true },
		);
		expect(result.acceptedChange).toBe(true);

		const projectLocks = spyOnProjectLocks();
		expect(titleOf(await cache.loadBoard(projectId))).toBe("Committed Title");
		expect(await cache.loadBoardRevision(projectId)).toBe(2);
		expect(projectLocks()).toBe(2);
		await cache.loadBoard(projectId);
		await cache.loadBoardRevision(projectId);
		expect(projectLocks()).toBe(2);
	});

	it("detects another process's atomic replacement and an in-place rewrite of the same size", async () => {
		const cache = new ProjectBoardReadCache();
		await cache.loadBoard(projectId);
		expect(await cache.loadBoardRevision(projectId)).toBe(1);

		await replaceExternally(getProjectMetaPath(projectId), (meta) => {
			meta.revision = 2;
		});
		expect(await cache.loadBoardRevision(projectId)).toBe(2);

		const boardPath = getProjectBoardPath(projectId);
		const raw = await readFile(boardPath, "utf8");
		const sameSize = raw.replace("Generated Title", "Generated Tit1e");
		expect(sameSize.length).toBe(raw.length);
		await writeFile(boardPath, sameSize, "utf8");
		expect(titleOf(await cache.loadBoard(projectId))).toBe("Generated Tit1e");
	});

	it("falls back to the locked path, which installs the journal, while a transaction is pending", async () => {
		const cache = new ProjectBoardReadCache();
		const before = await cache.loadBoard(projectId);
		const board = structuredClone(before) as RuntimeBoardData;
		const card = board.columns[1]?.cards[0];
		if (!card) throw new Error("Missing seeded card");
		card.title = "Journaled Title";
		const meta = JSON.parse(await readFile(getProjectMetaPath(projectId), "utf8")) as Record<string, unknown>;
		const sessions = JSON.parse(
			await readFile(join(getProjectDirectoryPath(projectId), "sessions.json"), "utf8").catch(() => "{}"),
		) as unknown;
		await writeFile(
			getProjectStateTransactionPath(projectId),
			JSON.stringify({ version: 1, board, sessions, meta: { ...meta, revision: 2 } }),
			"utf8",
		);

		const projectLocks = spyOnProjectLocks();
		expect(titleOf(await cache.loadBoard(projectId))).toBe("Journaled Title");
		expect(projectLocks()).toBe(1);
		await expect(readFile(getProjectStateTransactionPath(projectId), "utf8")).rejects.toMatchObject({
			code: "ENOENT",
		});
		expect(await cache.loadBoardRevision(projectId)).toBe(2);
	});

	it("takes the lock on every read when disabled", async () => {
		const cache = new ProjectBoardReadCache(false);
		const projectLocks = spyOnProjectLocks();
		await cache.loadBoard(projectId);
		await cache.loadBoard(projectId);
		await cache.loadBoardRevision(projectId);
		expect(projectLocks()).toBe(3);
	});

	it("lets the native title poll run without the project lock while the board is unchanged", async () => {
		const cache = new ProjectBoardReadCache();
		const session = createTestTaskSessionSummary({
			taskId: "task-1",
			agentId: "claude",
			resumeSessionId: "claude-session-1",
			sessionInstanceId: "launch-1",
			sessionLaunchPath: "/worktree",
		});
		const store = new InMemorySessionSummaryStore();
		vi.spyOn(store, "listSummaries").mockImplementation(() => [session]);
		vi.spyOn(store, "getSummary").mockImplementation(() => session);
		const terminalManager = {
			store,
			getTaskSessionProcessIdentity: () => ({
				pid: 123,
				sessionInstanceId: "launch-1",
				launchOperationId: null,
				agentId: "claude" as const,
				binary: "claude",
				profileEnvironment: { HOME: "/home/user" },
			}),
		};
		const readTitles = vi.fn(async () => new Map<string, string>());
		const monitor = createNativeTaskTitleMonitor(
			{
				listManagedProjects: () => [{ projectId, projectPath, terminalManager }],
				loadBoard: (id) => cache.loadBoard(id),
				boardCommands: { setGeneratedTaskTitle: vi.fn() },
				publishTitleUpdated: vi.fn(),
			},
			{ agentId: "claude", logTag: "test-native-title", resolveProfileKey: () => "profile", readTitles },
		);
		await monitor.refresh();
		readFileCalls.paths.length = 0;
		const projectLocks = spyOnProjectLocks();
		await monitor.refresh();
		await monitor.refresh();
		expect(readTitles).toHaveBeenCalledTimes(3);
		expect(projectLocks()).toBe(0);
		expect(stateFileReads()).toEqual([]);
		await monitor.close();
	});
});
