import { resolve } from "node:path";

import { describe, expect, it, vi } from "vitest";

import type { RuntimeBoardCard } from "../../../src/core";
import { createClaudeTaskTitleMonitor } from "../../../src/server/claude-task-title-monitor";
import type { ProjectBoardCommandService } from "../../../src/state";
import { InMemorySessionSummaryStore } from "../../../src/terminal";
import type { ClaudeCustomTitle } from "../../../src/title/claude-custom-titles";
import { createReviewBoard } from "../../utilities/board-factory";
import { createTestTaskSessionSummary } from "../../utilities/task-session-factory";

function renamed(title: string, revision = "record-1") {
	return new Map<string, ClaudeCustomTitle>([["claude-session-1", { title, revision }]]);
}

function harness(overrides: Partial<RuntimeBoardCard> = {}) {
	const board = createReviewBoard("task-1", "Fix title syncing");
	const card = board.columns.find((column) => column.id === "review")?.cards[0];
	if (!card) throw new Error("Missing test card");
	Object.assign(card, { title: "Generated Title", titleAutoGenerated: true, ...overrides });
	let session = createTestTaskSessionSummary({
		taskId: "task-1",
		agentId: "claude",
		resumeSessionId: "claude-session-1",
		sessionInstanceId: "launch-1",
		sessionLaunchPath: "/worktree",
	});
	const store = new InMemorySessionSummaryStore();
	vi.spyOn(store, "listSummaries").mockImplementation(() => [session]);
	vi.spyOn(store, "getSummary").mockImplementation(() => session);
	const manager = {
		store,
		getTaskSessionProcessIdentity: () => ({
			pid: 123,
			sessionInstanceId: session.sessionInstanceId ?? "",
			launchOperationId: null,
			agentId: "claude" as const,
			binary: "claude",
			profileEnvironment: { HOME: "/home/user", CLAUDE_CONFIG_DIR: "claude-profile" },
		}),
	};
	const hint = { providerId: "claude" as const, providerSessionId: "claude-session-1", sourcePath: "/hint.jsonl" };
	const getHint = vi.fn(() => hint);
	const readCustomTitles = vi.fn(async () => new Map<string, ClaudeCustomTitle>());
	const setGeneratedTaskTitle = vi.fn(
		async (...args: Parameters<ProjectBoardCommandService["setGeneratedTaskTitle"]>) => {
			const options = args[5] ?? {};
			const acceptedChange =
				card.title === options.expectedTitle &&
				(card.titleAutoGenerated === true) === options.expectedAutoGenerated &&
				Boolean(options.isCurrent?.(board));
			if (acceptedChange) Object.assign(card, { title: args[3], titleAutoGenerated: true });
			return { acceptedChange } as Awaited<ReturnType<ProjectBoardCommandService["setGeneratedTaskTitle"]>>;
		},
	);
	const publishTitleUpdated = vi.fn();
	const monitor = createClaudeTaskTitleMonitor({
		listManagedProjects: () => [{ projectId: "project-1", projectPath: "/project", terminalManager: manager }],
		loadBoard: async () => structuredClone(board),
		boardCommands: { setGeneratedTaskTitle },
		hints: { getHint },
		readCustomTitles,
		publishTitleUpdated,
	});
	return {
		monitor,
		card,
		hint,
		getHint,
		readCustomTitles,
		setGeneratedTaskTitle,
		publishTitleUpdated,
		navigate: () => {
			session = { ...session, resumeSessionId: "claude-session-2" };
		},
	};
}

describe("Claude task title monitor", () => {
	it("keeps the generated title until the exact session has a custom title", async () => {
		const h = harness();
		await h.monitor.refresh();
		expect(h.getHint).toHaveBeenCalledWith("project-1", "task-1", "claude-session-1");
		expect(h.readCustomTitles).toHaveBeenCalledWith(resolve("/worktree", "claude-profile"), [
			{ sessionId: "claude-session-1", hint: h.hint },
		]);
		expect(h.setGeneratedTaskTitle).not.toHaveBeenCalled();
		h.readCustomTitles.mockResolvedValue(renamed("Renamed In Claude"));
		await h.monitor.refresh();
		expect(h.card.title).toBe("Renamed In Claude");
		expect(h.publishTitleUpdated).toHaveBeenCalledWith({
			projectId: "project-1",
			taskId: "task-1",
			title: "Renamed In Claude",
		});
		await h.monitor.close();
	});

	it("adopts a repeated rename record after explicit regeneration, but not the same record", async () => {
		const h = harness();
		h.readCustomTitles.mockResolvedValue(renamed("Renamed In Claude"));
		await h.monitor.refresh();
		h.card.title = "Explicit regeneration";
		await h.monitor.refresh();
		expect(h.card.title).toBe("Explicit regeneration");
		h.readCustomTitles.mockResolvedValue(renamed("Renamed In Claude", "record-2"));
		await h.monitor.refresh();
		expect(h.card.title).toBe("Renamed In Claude");
		await h.monitor.close();
	});

	it("never overwrites a manual name", async () => {
		const h = harness({ title: "Manual", titleAutoGenerated: false });
		h.readCustomTitles.mockResolvedValue(renamed("Renamed In Claude"));
		await h.monitor.refresh();
		expect(h.readCustomTitles).not.toHaveBeenCalled();
		expect(h.card.title).toBe("Manual");
		await h.monitor.close();
	});

	it("rejects a late read after the task switches conversations", async () => {
		const h = harness();
		h.readCustomTitles.mockImplementation(async () => {
			h.navigate();
			return renamed("Late name");
		});
		await h.monitor.refresh();
		expect(h.setGeneratedTaskTitle).not.toHaveBeenCalled();
		await h.monitor.close();
	});
});
