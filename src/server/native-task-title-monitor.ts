import type { RuntimeBoardData, RuntimeTaskSessionSummary } from "../core";
import { createTaggedLogger, findCardInBoard, normalizeDiagnosticErrorClass } from "../core";
import type { ProjectBoardCommandService } from "../state";
import type { NativeTaskSessionProfileEnvironment, TerminalSessionManager } from "../terminal";

const POLL_INTERVAL_MS = 2_000;

export type NativeTaskTitleManagedProject = {
	projectId: string;
	projectPath: string | null;
	terminalManager: Pick<TerminalSessionManager, "store" | "getTaskSessionProcessIdentity">;
};

export interface NativeTaskTitleMonitorDependencies {
	listManagedProjects: () => NativeTaskTitleManagedProject[];
	loadBoard: (projectId: string) => Promise<RuntimeBoardData>;
	boardCommands: Pick<ProjectBoardCommandService, "setGeneratedTaskTitle">;
	publishTitleUpdated: (input: { projectId: string; taskId: string; title: string }) => Promise<void> | void;
}

export interface NativeTaskTitleTarget {
	projectId: string;
	taskId: string;
	providerSessionId: string;
}

/**
 * A provider name. `revision` identifies the provider record that set it, so a
 * repeated identical rename is a new observation; without it, only a changed
 * name is delivered.
 */
export interface NativeTaskTitleObservation {
	title: string;
	revision?: string;
}

/** Provider policy: where a live session's persisted name lives and how to read it. */
export interface NativeTaskTitleSource {
	agentId: "claude" | "codex";
	logTag: string;
	/** Sessions sharing a profile key are read together. */
	resolveProfileKey(input: { launchPath: string; profile: NativeTaskSessionProfileEnvironment }): string;
	/** Latest non-empty provider name per provider session id; missing ids keep their current title. */
	readTitles(
		profileKey: string,
		targets: readonly NativeTaskTitleTarget[],
	): Promise<ReadonlyMap<string, string | NativeTaskTitleObservation>>;
}

export interface NativeTaskTitleMonitor {
	start(): void;
	refresh(): Promise<void>;
	close(): Promise<void>;
}

/**
 * Native TUIs own their provider conversation. Follow their persisted name
 * updates read-only and adopt them through the board command service with the
 * same manual-edit and current-session fencing for every provider.
 */
export function createNativeTaskTitleMonitor(
	deps: NativeTaskTitleMonitorDependencies,
	source: NativeTaskTitleSource,
): NativeTaskTitleMonitor {
	const log = createTaggedLogger(source.logTag);
	let closed = false;
	let timer: NodeJS.Timeout | null = null;
	let pending: Promise<void> | null = null;
	// Treat polling as name-change delivery, so an unchanged provider name does not undo explicit regeneration.
	const observedNames = new WeakMap<NativeTaskTitleManagedProject["terminalManager"], Map<string, string>>();

	async function refreshProject(project: NativeTaskTitleManagedProject): Promise<void> {
		const { projectId, projectPath, terminalManager: manager } = project;
		if (!projectPath) return;
		const sessions = manager.store
			.listSummaries()
			.filter(
				(session) =>
					session.agentId === source.agentId &&
					session.resumeSessionId &&
					manager.getTaskSessionProcessIdentity(session.taskId),
			);
		const observations = observedNames.get(manager) ?? new Map<string, string>();
		observedNames.set(manager, observations);
		const liveTaskIds = new Set(sessions.map((session) => session.taskId));
		for (const taskId of observations.keys()) if (!liveTaskIds.has(taskId)) observations.delete(taskId);
		if (!sessions.length) return;
		const board = await deps.loadBoard(projectId);
		const groups = new Map<
			string,
			Array<{ target: NativeTaskTitleTarget; apply: (name: NativeTaskTitleObservation) => Promise<void> }>
		>();
		for (const session of sessions) {
			const card = findCardInBoard(board, session.taskId);
			const identity = manager.getTaskSessionProcessIdentity(session.taskId);
			const providerSessionId = session.resumeSessionId;
			if (
				!card ||
				!identity ||
				identity.agentId !== source.agentId ||
				identity.sessionInstanceId !== session.sessionInstanceId ||
				!providerSessionId
			)
				continue;
			// Missing provenance on a named legacy card is not permission to overwrite it.
			if (card.titleAutoGenerated === false || (card.title !== null && card.titleAutoGenerated !== true)) continue;
			const profileKey = source.resolveProfileKey({
				launchPath: session.sessionLaunchPath ?? projectPath,
				profile: identity.profileEnvironment,
			});
			const isCurrent = () => {
				if (
					closed ||
					!deps
						.listManagedProjects()
						.some(
							(current) =>
								current.projectId === projectId &&
								current.projectPath === projectPath &&
								current.terminalManager === manager,
						)
				)
					return false;
				const current: RuntimeTaskSessionSummary | null = manager.store.getSummary(session.taskId);
				const process = manager.getTaskSessionProcessIdentity(session.taskId);
				return (
					current?.agentId === source.agentId &&
					current.sessionInstanceId === session.sessionInstanceId &&
					current.resumeSessionId === providerSessionId &&
					process?.sessionInstanceId === identity.sessionInstanceId
				);
			};
			const group = groups.get(profileKey) ?? [];
			group.push({
				target: { projectId, taskId: card.id, providerSessionId },
				apply: async ({ title, revision }) => {
					if (!isCurrent()) return;
					const observation = JSON.stringify([
						card.createdAt,
						identity.sessionInstanceId,
						providerSessionId,
						profileKey,
						title,
						revision ?? null,
					]);
					if (observations.get(card.id) === observation) return;
					if (title === card.title) {
						observations.set(card.id, observation);
						return;
					}
					const result = await deps.boardCommands.setGeneratedTaskTitle(
						{ projectId, projectPath },
						card.id,
						card.createdAt,
						title,
						Date.now(),
						{ expectedTitle: card.title, expectedAutoGenerated: card.titleAutoGenerated === true, isCurrent },
					);
					if (result.acceptedChange) {
						observations.set(card.id, observation);
						await deps.publishTitleUpdated({ projectId, taskId: card.id, title });
					}
				},
			});
			groups.set(profileKey, group);
		}
		for (const [profileKey, entries] of groups) {
			const titles = await source.readTitles(
				profileKey,
				entries.map((entry) => entry.target),
			);
			for (const entry of entries) {
				const name = titles.get(entry.target.providerSessionId);
				const observation = typeof name === "string" ? { title: name } : name;
				if (observation?.title) await entry.apply(observation);
			}
		}
	}

	function refresh(): Promise<void> {
		if (closed) return Promise.resolve();
		if (pending) return pending;
		pending = (async () => {
			for (const project of deps.listManagedProjects()) {
				if (closed) break;
				try {
					await refreshProject(project);
				} catch (error) {
					log.debug("Native task title metadata unavailable", {
						projectId: project.projectId,
						errorClass: error instanceof Error ? normalizeDiagnosticErrorClass(error.name) : "UnknownError",
					});
				}
			}
		})().finally(() => {
			pending = null;
		});
		return pending;
	}

	function schedule(): void {
		if (closed || timer) return;
		timer = setTimeout(() => {
			timer = null;
			void refresh().finally(schedule);
		}, POLL_INTERVAL_MS);
		timer.unref();
	}

	return {
		start: schedule,
		refresh,
		async close(): Promise<void> {
			closed = true;
			if (timer) clearTimeout(timer);
			timer = null;
			await pending;
		},
	};
}
